# DPES-824 reader for mutmut 3.8.0 seeded-case results (scratch only). Read-only over fixture meta and run records.
# Usage: python3 -I dpes824_reader.py <fixture-dir> <record-dir> <run-nonce> [mutmut-rc]
# Prints one verdict line per mutant, then one JSON summary line last. Verdicts are the output; the reader
# always exits 0.
#
# Rules follow docs/verification/mutation-toolchain-lock.md. Two deliberate differences from mutmut's own
# status_by_exit_code table (mutmut 3.8.0 stats.py):
#   - exit 3 (internal test-runner error) is reader-error, never killed.
#   - exit 1 is killed only when this run's record for that mutant agrees: same nonce and mutant key, exit 1,
#     collected >= 1, failed >= 1, and a sentinel that repeats those values.
# Control records (clean run "", forced-fail probe "fail", dry run "stats") are reported, never counted.
import json
import os
import sys

CONTROL = {"": "clean", "fail": "forced-fail", "stats": "stats"}
TIMEOUT = {36, -24, 24, 152, 255}
SEGFAULT = {-9, -11}
NO_TESTS = {5, 33}
TOOL_MISSING = {126, 127}
REQUIRED = ("nonce", "mutant", "collected", "failed", "exit", "pid", "sentinel")


def load_meta(fixture):
    out = {}
    for root, _, files in os.walk(os.path.join(fixture, "mutants")):
        for f in files:
            if f.endswith(".meta"):
                with open(os.path.join(root, f), encoding="utf-8") as fh:
                    out.update(json.load(fh).get("exit_code_by_key", {}))
    return out


def load_records(rec_dir, nonce):
    recs, other, malformed = [], [], []
    names = sorted(os.listdir(rec_dir)) if os.path.isdir(rec_dir) else []
    for name in names:
        if not name.endswith(".json"):
            continue
        try:
            with open(os.path.join(rec_dir, name), encoding="utf-8") as fh:
                rec = json.load(fh)
        except (OSError, ValueError):
            malformed.append(name)
            continue
        if (
            not isinstance(rec, dict)
            or any(k not in rec for k in REQUIRED)
            or any(
                not isinstance(rec[k], str)
                for k in ("nonce", "mutant", "sentinel")
            )
            or any(
                type(rec[k]) is not int
                for k in ("collected", "failed", "exit", "pid")
            )
            or rec["collected"] < 0
            or rec["failed"] < 0
            or rec["pid"] < 1
        ):
            malformed.append(name)
        elif rec["nonce"] != nonce:
            other.append(name)
        else:
            recs.append(rec)
    return recs, other, malformed


def sentinel_ok(rec):
    expect = (
        f"DPES824-SENTINEL nonce={rec['nonce']} mutant={rec['mutant']} "
        f"collected={rec['collected']} failed={rec['failed']} exit={rec['exit']}"
    )
    return rec["sentinel"] == expect


def verdict(code, rec, duplicated):
    if code is None:
        # Generated by mutmut but never given an exit code: it did not run, so it cannot count as killed or survived.
        return "reader-error (mutant generated, not run)"
    if duplicated:
        return "reader-error (duplicate run records)"
    if rec is not None and not sentinel_ok(rec):
        return "reader-error (sentinel disagrees with record)"
    if code == 0:
        if rec is None:
            return "reader-error (no run record)"
        if rec["exit"] != 0:
            return "reader-error (record exit %s, mutmut exit 0)" % rec["exit"]
        return "survived"
    if code == 1:
        if rec is None:
            return "reader-error (no run record)"
        if rec["exit"] != 1:
            return "reader-error (record exit %s, mutmut exit 1)" % rec["exit"]
        if rec["collected"] < 1 or rec["failed"] < 1:
            return "reader-error (record does not show a kill)"
        return "killed"
    if code in TIMEOUT:
        return "timeout" + (" (255 unverified)" if code == 255 else "")
    if code == 3:
        return "reader-error (internal test-runner error)"
    if code in NO_TESTS:
        return "no tests"
    if code == 34:
        return "skipped"
    if code in SEGFAULT:
        return "segfault"
    if code in TOOL_MISSING:
        return "reader-error (tool not found)"
    if code == 37:
        return "caught by type check"
    if code == 35:
        return "suspicious"
    if code == 2:
        return "interrupted"
    if code == 4:
        return "abort (usage or configuration error)"
    return "reader-error (unlisted exit %s)" % code


def dry_run(stats):
    if stats:
        r = stats[-1]
        if r["collected"] < 1 or r["exit"] != 0:
            return "aborted (stats collected=%s exit=%s)" % (r["collected"], r["exit"])
        return "ok (stats collected=%s exit=0)" % r["collected"]
    return "no stats record"


def main():
    fixture, rec_dir, nonce = sys.argv[1], sys.argv[2], sys.argv[3]
    mutmut_rc = sys.argv[4] if len(sys.argv) > 4 else None
    meta = load_meta(fixture)
    records, other, malformed = load_records(rec_dir, nonce)

    controls = {label: [r for r in records if r["mutant"] == key] for key, label in CONTROL.items()}
    mutant_recs = [r for r in records if r["mutant"] not in CONTROL]
    by_key, seen, dups = {}, set(), set()
    for r in mutant_recs:
        if r["mutant"] in seen:
            dups.add(r["mutant"])
        seen.add(r["mutant"])
        by_key[r["mutant"]] = r

    dry = dry_run(controls["stats"])
    run_verdict = None
    if dry.startswith("aborted"):
        # A selection that matches no tests aborts the dry run: nothing is counted.
        run_verdict = "not counted (dry run %s)" % dry
        verdicts = {k: "not counted (dry run aborted)" for k in sorted(meta)}
    else:
        if dry == "no stats record" and mutmut_rc not in (None, "0"):
            # Run failed before its dry run was recorded, e.g. the test runner could not import.
            run_verdict = "reader-error (run ended rc %s before dry run; no stats record)" % mutmut_rc
        verdicts = {k: verdict(meta[k], by_key.get(k), k in dups) for k in sorted(meta)}
    summary = {}
    for v in verdicts.values():
        summary[v] = summary.get(v, 0) + 1

    out = {
        "fixture": os.path.basename(fixture),
        "nonce": nonce,
        "mutmut_rc": mutmut_rc,
        "dry_run": dry_run(controls["stats"]),
        "mutants_in_meta": len(meta),
        "control_clean": [r["collected"] for r in controls["clean"]],
        "control_forced_fail": [[r["collected"], r["failed"], r["exit"]] for r in controls["forced-fail"]],
        "control_forced_fail_ok": all(r["exit"] == 1 and r["failed"] >= 1 for r in controls["forced-fail"]) if controls["forced-fail"] else None,
        "records_mutant": len(mutant_recs),
        "records_other_nonce": other,
        "records_malformed": malformed,
        "mapping_unmapped_records": sorted(set(by_key) - set(meta)),
        "mapping_duplicate_records": sorted(dups),
        "mapping_killed_without_record": sorted(k for k, c in meta.items() if c == 1 and k not in by_key),
        "mapping_timeout_with_record": sorted(k for k, c in meta.items() if c in TIMEOUT and k in by_key),
        "verdicts": verdicts,
        "summary": summary,
    }
    out["run_verdict"] = run_verdict
    if run_verdict:
        print(f"{run_verdict:<52} (run)  mutmut_rc={mutmut_rc}")
    for key in sorted(verdicts):
        print(f"{verdicts[key]:<52} {key}  mutmut_exit={meta[key]}")
    print(json.dumps(out, sort_keys=True))


if __name__ == "__main__":
    main()
